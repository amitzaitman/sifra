// Generates data/skills.js, data/errors.js, data/forms.js and data/models.js from the docs.
// Run: npm run gen. tests/sync.test.js regenerates in memory and compares byte for byte.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  DEPTH, ERRORS, MEANING, ROOT, SHARED, SKILLS, listFiles, parseCatalogue, parseForms, parseModels,
  parseParams, parseRequires, parseSkills, parseStrands, read, ticked,
} from './docs-parse.js';

const HEAD = '// Generated by scripts/gen-data.js from the docs. Do not edit: change the docs and run npm run gen.\n';

/**
 * An array as a module export, one JSON entry per line.
 * @param {string} name
 * @param {string} type JSDoc type
 * @param {unknown[]} list
 * @returns {string}
 */
function arrayModule(name, type, list) {
  return `${HEAD}/** @type {${type}} */\nexport const ${name} = [\n${list.map((x) => `  ${JSON.stringify(x)},`).join('\n')}\n];\n`;
}

/**
 * An object as a module export, one JSON entry per line.
 * @param {string} name
 * @param {string} type JSDoc type
 * @param {Record<string, unknown>} object
 * @returns {string}
 */
function objectModule(name, type, object) {
  const lines = Object.entries(object).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return `${HEAD}/** @type {${type}} */\nexport const ${name} = {\n${lines.join('\n')}\n};\n`;
}

/**
 * The learning order (architecture 3.6, pedagogy 5.12): the rows sorted by prerequisite depth (the
 * longest chain of base prerequisites below a skill), then by row order. Every base prerequisite
 * is shallower than its skill, so this is a topological order. Conditional prerequisites gate a
 * level at run time, not the order. No grade: progression is independent of school grade (owner
 * decision 2026-10-14). An explicit sequence column could later replace the row-order tie-break.
 * @template {{ id: string, requires: { base: string[] } }} T
 * @param {T[]} rows in skills.md row order
 * @returns {T[]}
 */
export function learningOrder(rows) {
  const byId = new Map(rows.map((row) => [row.id, row]));
  const depth = new Map();
  const depthOf = (id, path = []) => {
    if (path.includes(id)) throw new Error(`prerequisite cycle: ${[...path, id].join(' > ')}`);
    if (!depth.has(id)) {
      const below = byId.get(id).requires.base.filter((p) => byId.has(p)).map((p) => depthOf(p, [...path, id]) + 1);
      depth.set(id, Math.max(0, ...below));
    }
    return depth.get(id);
  };
  const row = new Map(rows.map((r, i) => [r.id, i]));
  return [...rows].sort((a, b) => depthOf(a.id) - depthOf(b.id) || row.get(a.id) - row.get(b.id));
}

/**
 * The generated files, by repo path.
 * @returns {Map<string, string>}
 */
export function generate() {
  const skillsText = read(SKILLS);
  const { skills } = parseSkills(skillsText, parseStrands(skillsText));
  const catalogue = parseCatalogue(read(ERRORS));
  const ordered = learningOrder([...skills.values()].map((row) => ({
    id: row.id,
    requires: parseRequires(row.prereqs),
    rules: row.rules.includes('מועמדים') ? [] : ticked(row.rules).filter((r) => catalogue.rules.has(r)),
  })));
  const rules = Object.fromEntries(
    [...catalogue.rules].map(([id, displays]) => [id, { types: catalogue.types.get(id), display: displays[0] }]),
  );
  const models = parseParams(skillsText).get('model')?.values ?? [];
  const strandFiles = listFiles(['.md'], join(ROOT, DEPTH)).filter((f) => f !== SHARED && f !== ERRORS);
  return new Map([
    ['data/skills.js', arrayModule('SKILLS', 'Skill[]', ordered)],
    ['data/errors.js', objectModule('RULES', 'Record<string, RuleInfo>', rules)],
    ['data/forms.js', arrayModule('FORMS', 'FormRow[]', parseForms(read(MEANING)))],
    ['data/models.js', objectModule('MODEL_ORDER', 'Record<string, string[]>', parseModels(strandFiles.map(read), models))],
  ]);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const [path, text] of generate()) {
    writeFileSync(join(ROOT, path), text);
    console.log(`wrote ${path}`);
  }
}
